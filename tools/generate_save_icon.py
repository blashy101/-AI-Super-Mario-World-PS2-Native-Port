#!/usr/bin/env python3
"""Build an original, smooth 3D Yoshi egg in the PS2 Browser icon format.

Format references: PS2SDK mcIcon, ps2homebrew/HDLGameInstaller IconLoader.h.
The mesh, colors and lighting are generated here; no external artwork is used.
"""
from pathlib import Path
import math
import struct

ROOT = Path(__file__).resolve().parents[1]

def model():
    vertices = bytearray()
    longitude, latitude = 12, 8
    def point(i, j):
        t, a = math.pi*i/latitude, 2*math.pi*j/longitude
        r = math.sin(t)*(0.82-0.16*math.cos(t))
        return (r*math.sin(a), -1.2*math.cos(t), r*math.cos(a))
    def vertex(i, j, color):
        x,y,z = point(i,j)
        # Surface gradient gives a smooth normal, with the original egg taper.
        t=math.pi*i/latitude; a=2*math.pi*j/longitude
        dr=math.cos(t)*(0.82-0.16*math.cos(t))+0.16*math.sin(t)**2
        nx,ny,nz=1.2*math.sin(t)*math.sin(a),-dr,1.2*math.sin(t)*math.cos(a)
        length=math.sqrt(nx*nx+ny*ny+nz*nz)
        return struct.pack('<8h2h4B',round(x*1024),round(y*1024),round(z*1024),0,
                           round(nx/length*4096),round(ny/length*4096),round(nz/length*4096),0,
                           0,0,*color,128)
    # Broad green spots distributed around the cream shell.
    spots=[(2.2,1,1.0),(4,4,1.3),(6,1.5,1.15),(2.5,8,1.05),(5.5,9,1.2),(4,11.5,1.0)]
    for i in range(latitude):
        for j in range(longitude):
            spot=any(((i+0.5-y)/r)**2+(min(abs(j+0.5-x),longitude-abs(j+0.5-x))/r)**2<1 for y,x,r in spots)
            color=(35,108,44) if spot else (124,120,104)
            # The icon coordinate system has Y pointing down. Outward winding.
            for tri in (((i,j),(i+1,j),(i+1,j+1)),((i,j),(i+1,j+1),(i,j+1))):
                if i==0 and tri[0][0]==tri[2][0]: continue
                if i==latitude-1 and tri[1][0]==tri[2][0]: continue
                for a,b in (tri[0],tri[2],tri[1]): vertices+=vertex(a,b,color)
    out=struct.pack('<IIIfI',0x10000,1,15,1.0,len(vertices)//24)+vertices
    out+=struct.pack('<IIfIIIIff',1,1,1.0,0,1,0,1,0.0,1.0)
    # Valid 128x128 PSMCT16 white texture, compressed to one RLE run.
    out+=struct.pack('<IhH',4,16384,0xffff)
    return out

def descriptor():
    b=bytearray(964)
    struct.pack_into('<4sHHII',b,0,b'PS2D',0,22,0,0x60)
    for i,c in enumerate(((24,48,42,0),(24,48,42,0),(8,24,24,0),(8,24,24,0))):
        struct.pack_into('<4I',b,16+i*16,*c)
    for i,d in enumerate(((-0.5,-0.7,0.5,0),(0.7,-0.3,0.4,0),(-0.2,0.5,0.7,0))):
        struct.pack_into('<4f',b,80+i*16,*d)
    for i,c in enumerate(((0.7,0.7,0.65,0),(0.3,0.35,0.3,0),(0.15,0.2,0.2,0))):
        struct.pack_into('<4f',b,128+i*16,*c)
    struct.pack_into('<4f',b,176,0.35,0.35,0.35,0)
    title=''.join('\u3000' if c==' ' else chr(ord(c)+0xfee0) for c in 'Super Mario World').encode('shift_jis')
    b[192:192+len(title)]=title
    for at in (260,324,388): b[at:at+10]=b'yoshi.icn\0'
    return bytes(b)

def main():
    files={'icon.sys':descriptor(),'yoshi.icn':model()}
    folder=ROOT/'data/save_icon'; folder.mkdir(parents=True,exist_ok=True)
    source=['/* Generated by tools/generate_save_icon.py. Original PS2 3D egg. */']
    for name,data in files.items():
        (folder/name).write_bytes(data)
        source.append('static const unsigned char '+name.replace('.','_')+'[]={')
        for i in range(0,len(data),24):source.append(','.join('0x%02x'%x for x in data[i:i+24])+',')
        source.append('};')
        print(name,len(data))
    (ROOT/'src/save_icon_data.h').write_text('\n'.join(source)+'\n')

if __name__=='__main__': main()
